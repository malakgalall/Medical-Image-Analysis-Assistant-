def extract_glcm_features(img):
    gray = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)
    glcm = graycomatrix(gray, distances=[1],
                        angles=[0, np.pi/4, np.pi/2, 3*np.pi/4],
                        levels=256, symmetric=True, normed=True)
    features = {}
    for prop in ['contrast', 'homogeneity', 'energy', 'correlation']:
        features[f'glcm_{prop}'] = np.mean(graycoprops(glcm, prop))
    return features


def extract_lbp_features(img):
    gray          = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)
    mask          = get_segmentation_mask(img)
    lbp           = local_binary_pattern(gray, 24, 3, method='uniform')
    lesion_pixels = lbp[mask == 255]

    hist, _ = np.histogram(lesion_pixels, bins=26, range=(0, 26), density=True)

    features = {f'lbp_bin_{i}': hist[i] for i in range(26)}
    features['lbp_mean']    = np.mean(lesion_pixels)
    features['lbp_std']     = np.std(lesion_pixels)
    features['lbp_entropy'] = -np.sum(hist * np.log2(hist + 1e-10))

    return features, lbp, mask

def extract_shape_features(img):
    mask        = get_segmentation_mask(img)
    contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

    if not contours:
        return {'area': 0, 'perimeter': 0, 'circularity': 0,
                'solidity': 0, 'aspect_ratio': 0}

    c         = max(contours, key=cv2.contourArea)
    area      = cv2.contourArea(c)
    perimeter = cv2.arcLength(c, True)
    hull_area = cv2.contourArea(cv2.convexHull(c))
    _, _, w, h = cv2.boundingRect(c)

    return {
        'area':         area,
        'perimeter':    perimeter,
        'circularity':  (4 * np.pi * area / perimeter ** 2) if perimeter > 0 else 0,
        'solidity':     area / hull_area if hull_area > 0 else 0,
        'aspect_ratio': w / h if h > 0 else 0
    }

