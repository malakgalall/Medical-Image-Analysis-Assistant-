def preprocess(img_path):
    img = cv2.imread(img_path)
    img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

    # CLAHE enhancement
    lab = cv2.cvtColor(img, cv2.COLOR_RGB2LAB)
    l,a,b = cv2.split(lab)

    clahe = cv2.createCLAHE(2.0, (8,8))
    l = clahe.apply(l)

    img = cv2.cvtColor(cv2.merge((l,a,b)), cv2.COLOR_LAB2RGB)

    # Hair removal
    gray = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)
    kernel = cv2.getStructuringElement(cv2.MORPH_RECT, (15,15))
    blackhat = cv2.morphologyEx(gray, cv2.MORPH_BLACKHAT, kernel)

    _, mask = cv2.threshold(blackhat, 10, 255, cv2.THRESH_BINARY)
    img = cv2.inpaint(img, mask, 3, cv2.INPAINT_TELEA)

    return img

def crop(img):
    gray = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)
    blur = cv2.GaussianBlur(gray, (7,7), 0)

    _, mask = cv2.threshold(blur, 0, 255,
                            cv2.THRESH_BINARY_INV + cv2.THRESH_OTSU)

    contours,_ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

    if contours:
        c = max(contours, key=cv2.contourArea)
        x,y,w,h = cv2.boundingRect(c)
        img = img[y:y+h, x:x+w]

    return cv2.resize(img, (128,128))

from skimage.feature import hog, local_binary_pattern, graycomatrix, graycoprops

def extract_features(img):

    gray = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)

    # HOG
    hog_feat = hog(gray, pixels_per_cell=(16,16),
                   cells_per_block=(2,2),
                   feature_vector=True)

    # LBP
    lbp = local_binary_pattern(gray, 24, 3, method='uniform')
    lbp_hist, _ = np.histogram(lbp, bins=26, range=(0,26), density=True)

    # GLCM
    glcm = graycomatrix(gray, [1], [0], 256, symmetric=True, normed=True)

    contrast = graycoprops(glcm, 'contrast')[0,0]
    energy   = graycoprops(glcm, 'energy')[0,0]

    # Color features
    color = img.mean(axis=(0,1))

    return np.hstack([hog_feat[:80], lbp_hist, [contrast, energy], color])

