def kmeans_segmentation(img, K=2):

    image = img.copy()

    pixel_vals = image.reshape((-1, 3))
    pixel_vals = np.float32(pixel_vals)

    criteria = (cv2.TERM_CRITERIA_EPS +
                cv2.TERM_CRITERIA_MAX_ITER, 100, 0.2)

    _, labels, centers = cv2.kmeans(pixel_vals,
                                    K,
                                    None,
                                    criteria,
                                    10,
                                    cv2.KMEANS_RANDOM_CENTERS)

    centers = np.uint8(centers)
    segmented = centers[labels.flatten()]
    segmented = segmented.reshape(image.shape)

    gray = cv2.cvtColor(segmented, cv2.COLOR_RGB2GRAY)

    _, mask = cv2.threshold(gray, 0, 255,
                            cv2.THRESH_BINARY_INV + cv2.THRESH_OTSU)

    return segmented, mask

"""Threshold Segmentation"""

def threshold_segmentation(img):

    gray = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)

    blurred = cv2.GaussianBlur(gray, (7, 7), 0)

    _, mask = cv2.threshold(blurred,
                            0,
                            255,
                            cv2.THRESH_BINARY_INV + cv2.THRESH_OTSU)

    return mask

"""IoU Metric"""

def compute_iou(mask1, mask2):

    mask1 = mask1 > 0
    mask2 = mask2 > 0

    intersection = np.logical_and(mask1, mask2).sum()
    union = np.logical_or(mask1, mask2).sum()

    return intersection / union if union != 0 else 0

"""Ground Truth"""

def get_gt(img):

    gray = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)

    blurred = cv2.GaussianBlur(gray, (7,7), 0)

    _, th = cv2.threshold(blurred, 0, 255,
                          cv2.THRESH_BINARY_INV + cv2.THRESH_OTSU)

    contours, _ = cv2.findContours(th,
                                   cv2.RETR_EXTERNAL,
                                   cv2.CHAIN_APPROX_SIMPLE)

    contour_mask = np.zeros_like(gray)
    cv2.drawContours(contour_mask, contours, -1, 255, -1)

    mask = np.zeros(img.shape[:2], np.uint8)

    bgdModel = np.zeros((1,65), np.float64)
    fgdModel = np.zeros((1,65), np.float64)

    h, w = img.shape[:2]
    rect = (int(w*0.1), int(h*0.1), int(w*0.8), int(h*0.8))

    cv2.grabCut(img, mask, rect,
                bgdModel, fgdModel,
                5, cv2.GC_INIT_WITH_RECT)

    grab_mask = np.where((mask==2)|(mask==0),
                         0, 255).astype('uint8')

    final_gt = cv2.bitwise_and(contour_mask, grab_mask)

    return final_gt

"""Dice + Precision + Recall"""

def dice_score(y_true, y_pred):
    y_true = y_true > 0
    y_pred = y_pred > 0

    inter = np.logical_and(y_true, y_pred).sum()
    return (2 * inter) / (y_true.sum() + y_pred.sum() + 1e-10)


def precision_score(y_true, y_pred):
    y_true = y_true > 0
    y_pred = y_pred > 0

    tp = np.logical_and(y_true, y_pred).sum()
    fp = np.logical_and(~y_true, y_pred).sum()

    return tp / (tp + fp + 1e-10)


def recall_score(y_true, y_pred):
    y_true = y_true > 0
    y_pred = y_pred > 0

    tp = np.logical_and(y_true, y_pred).sum()
    fn = np.logical_and(y_true, ~y_pred).sum()

    return tp / (tp + fn + 1e-10)

