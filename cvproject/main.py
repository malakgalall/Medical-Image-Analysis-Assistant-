def harris_corner_scratch_with_mask(img, mask, k=0.04, threshold_ratio=0.001):
    img_copy = img.copy()
    gray = cv2.cvtColor(img_copy, cv2.COLOR_RGB2GRAY).astype(np.float32)

    Ix = cv2.Sobel(gray, cv2.CV_64F, 1, 0, ksize=3)
    Iy = cv2.Sobel(gray, cv2.CV_64F, 0, 1, ksize=3)

    Ixx, Iyy, Ixy = Ix**2, Iy**2, Ix*Iy

    Sxx = gaussian_filter(Ixx, sigma=1)
    Syy = gaussian_filter(Iyy, sigma=1)
    Sxy = gaussian_filter(Ixy, sigma=1)

    det_M = (Sxx * Syy) - (Sxy ** 2)
    trace_M = Sxx + Syy
    R = det_M - k * (trace_M ** 2)

    R[mask == 0] = 0

    R_max = R.max()
    img_copy[R > threshold_ratio * R_max] = [255, 0, 0]

    return img_copy

