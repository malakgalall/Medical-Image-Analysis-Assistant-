def harris_corner_scratch(img, k=0.04, threshold_ratio=0.01):
    img_copy = img.copy()

    # 1. Convert to Grayscale
    gray = cv2.cvtColor(img_copy, cv2.COLOR_RGB2GRAY).astype(np.float32)

    # 2. Compute spatial derivatives (Ix, Iy) using Sobel filter
    Ix = cv2.Sobel(gray, cv2.CV_64F, 1, 0, ksize=3)
    Iy = cv2.Sobel(gray, cv2.CV_64F, 0, 1, ksize=3)

    # 3. Compute products of derivatives at each pixel
    Ixx = Ix ** 2
    Iyy = Iy ** 2
    Ixy = Ix * Iy

    # 4. Apply Gaussian blur to compute the sum of products (Structure Tensor components)
    # sigma=1 is a standard choice for the window function
    Sxx = gaussian_filter(Ixx, sigma=1)
    Syy = gaussian_filter(Iyy, sigma=1)
    Sxy = gaussian_filter(Ixy, sigma=1)

    # 5. Compute the Harris response for each pixel
    # R = det(M) - k * (trace(M))^2
    det_M = (Sxx * Syy) - (Sxy ** 2)
    trace_M = Sxx + Syy
    R = det_M - k * (trace_M ** 2)

    # 6. Apply Thresholding to identify corners
    # Any response greater than the ratio * max_response is considered a corner
    R_max = R.max()
    img_copy[R > threshold_ratio * R_max] = [255, 0, 0] # Color the corners RED

    return img_copy

