def get_matches(desc1, desc2, ratio=0.75):
    matches = cv2.BFMatcher(cv2.NORM_L2).knnMatch(desc1, desc2, k=2)
    good    = []
    for match in matches:
        if len(match) == 2:
            m, n = match
            if m.distance < ratio * n.distance:
                good.append(m)
    return good

